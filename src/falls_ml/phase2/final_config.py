def _rel(path: str | Path) -> str:
    """A path as the project declares it: relative paths unchanged (``/`` separators), absolute ones relative to the project root found from
    this module (never from the current working directory), else the file name - identical on every machine and working directory."""
    from falls_ml.paths import portable_path, project_relative_posix

    p = Path(path)
    if not p.is_absolute():
        return portable_path(p)
    return project_relative_posix(p, Path(__file__)) or p.name


def to_bytes(cfg: dict[str, Any]) -> bytes:
    return (json.dumps(cfg, indent=2, ensure_ascii=False, sort_keys=False) + "\n").encode("utf-8")


def sha256_of(cfg: dict[str, Any]) -> str:
    return hashlib.sha256(to_bytes(cfg)).hexdigest()


