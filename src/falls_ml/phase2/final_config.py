def load_frozen() -> tuple[bytes | None, str | None]:
    """(bytes, sha256) of the repository's frozen FINAL_EXPERIMENT_CONFIG.json, or (None, None) when it is missing."""
    p = resolve_path(FROZEN_PATH)
    if not p.is_file():
        return None, None
    b = p.read_bytes()
    return b, hashlib.sha256(b).hexdigest()


def sha_line(sha: str) -> str:
    return f"{sha}  FINAL_EXPERIMENT_CONFIG.json\n"
