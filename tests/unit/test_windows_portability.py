"""Windows portability guards. Windows 10/11 x64 (CMD, ANSI code pages such as cp1252/cp1255, 260-character paths) is a supported
runtime, but development and CI run on macOS, so Windows-only failure modes are caught here statically (AST, never regex) or by
simulating the Windows behaviour on the current OS.

Static rules (``src/``, ``tests/``, ``tools/``, ``scripts/handoff/``):
- every text-mode ``open``/``Path.open``/``read_text``/``write_text``/``NamedTemporaryFile``/``TextIOWrapper`` passes ``encoding``
  (the Windows default is the ANSI code page, not UTF-8);
- ``subprocess`` text mode passes ``encoding``; no ``shell=True``, ``os.system``, ``os.popen`` or ``subprocess.getoutput``;
- no Unix-only modules (``fcntl``, ``resource``, ``pwd``, ``grp``, ``termios``, ...) or POSIX-only ``os``/``signal`` calls;
- artifacts written by ``src/`` and generated by ``tools/`` use LF line endings (``newline="\\n"``, ``lineterminator="\\n"``),
  so outputs are byte-identical across operating systems;
- tests that create symlinks handle ``OSError`` or skip on Windows;
- no reserved Windows file names, invalid characters, trailing dots/spaces or case-only collisions in the shipped tree.
"""

