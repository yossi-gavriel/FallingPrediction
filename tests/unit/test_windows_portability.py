def test_replace_file_retries_windows_sharing_violations(tmp_path, monkeypatch):
    from falls_ml import artifacts

    src, dst = tmp_path / "src.json", tmp_path / "dst.json"
    src.write_text("{}", encoding="utf-8")
    real_replace, attempts, sleeps = os.replace, [], []

    def flaky(a, b):
        attempts.append(1)
        if len(attempts) < 3:
            raise PermissionError(13, "The process cannot access the file because it is being used by another process")
        real_replace(a, b)

    monkeypatch.setattr(artifacts.os, "replace", flaky)
    artifacts.replace_file(src, dst, windows=True, sleep=sleeps.append)
    assert dst.read_text(encoding="utf-8") == "{}" and len(attempts) == 3 and sleeps == [0.05, 0.1]

    def locked(a, b):
        raise PermissionError(13, "in use")

    monkeypatch.setattr(artifacts.os, "replace", locked)
    src.write_text("{}", encoding="utf-8")
    with pytest.raises(PermissionError, match="after 10 attempts.*in use by another process") as excinfo:
        artifacts.replace_file(src, dst, windows=True, sleep=sleeps.append)
    assert str(dst) in str(excinfo.value) and max(sleeps) == 0.5
    with pytest.raises(PermissionError, match="^\\[Errno 13\\] in use$"):
        artifacts.replace_file(src, dst, windows=False, sleep=sleeps.append)
    with pytest.raises(PermissionError):
        artifacts.write_json(tmp_path / "out.json", {"a": 1})
    assert not list(tmp_path.glob(".out.json.tmp")), "the temp file is removed when the replace fails"


def test_git_commit_survives_undecodable_output_and_foreign_repositories(tmp_path, monkeypatch):
    from falls_ml import artifacts

    def undecodable(*args, **kwargs):
        raise UnicodeDecodeError("charmap", b"\x9d", 0, 1, "character maps to <undefined>")

    monkeypatch.setattr(artifacts.subprocess, "run", undecodable)
    assert artifacts.git_commit(tmp_path) is None
    monkeypatch.undo()
    git = shutil.which("git")
    if git is None or subprocess.run([git, "--version"], capture_output=True, check=False).returncode != 0:
        pytest.skip("git not available")
    repo = tmp_path / "repo"
    (repo / "handoff").mkdir(parents=True)
    ident = ["-c", "user.name=test", "-c", "user.email=test@example.org", "-c", "core.quotepath=false", "-c", "commit.gpgsign=false"]
    for args in (["init", "-q"], ["add", "-A"], ["commit", "-q", "--allow-empty", "-m", "init"]):
        subprocess.run([git, *ident, *args], cwd=repo, capture_output=True, check=True, env=utf8_env(GIT_CONFIG_NOSYSTEM="1"))
