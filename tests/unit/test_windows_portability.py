def test_scanners_detect_violations(tmp_path, monkeypatch):
    """The scanners must flag the patterns they exist for (a scanner that finds nothing proves nothing)."""
    monkeypatch.setattr(sys.modules[__name__], "ROOT", tmp_path)
    bad = tmp_path / "src" / "bad.py"
    bad.parent.mkdir()
    bad.write_text(
        "import fcntl, os, subprocess, tempfile, io\nfrom pathlib import Path\n"
        "def f(p, zf):\n"
        "    open(p).read(); open(p, 'w'); Path(p).read_text(); Path(p).write_text('x'); Path(p).open('a')\n"
        "    tempfile.NamedTemporaryFile('w'); io.TextIOWrapper(p); os.fdopen(3, 'w')\n"
        "    subprocess.run(['x'], text=True); subprocess.run('x', shell=True); os.system('x'); os.getuid()\n"
        "    p.to_csv('a.csv'); Path(p).symlink_to(p)\n"
        "    open(p, 'rb'); open(p, encoding='utf-8'); Path(p).read_text('utf-8'); zf.open('member.txt'); Path(p).open('rb')\n"
        "    subprocess.run(['x'], text=True, encoding='utf-8'); tempfile.NamedTemporaryFile()\n", encoding="utf-8")
    encoding_rules = [s.rule for s in text_io_without_encoding(bad)]
    assert len(encoding_rules) == 9, encoding_rules
    assert len(lf_artifact_writes(bad)) == 3
    assert sorted(s.rule.split()[0] for s in shell_and_posix_only(bad)) == ["POSIX-only", "Unix-only", "os.system()", "shell=True"]
    assert len(unguarded_symlinks(bad)) == 1
    # join as text: on Windows `path / "a:b.csv"` treats "a:" as a drive and discards the folder
    names = [Path(f"{tmp_path / 'src'}{os.sep}{n}") for n in ("aux.txt", "COM1", "report.", "a:b.csv", "Readme.md", "README.md")]
    problems = windows_name_problems(names)
    assert len(problems) == 5 and any("differ only in case" in p for p in problems)


