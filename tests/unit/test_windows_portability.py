def test_source_tree_hash_is_os_independent(tmp_path):
    from falls_ml.artifacts import source_tree_sha256

    # "B.py" < "a.py" only in case-sensitive order (Windows Path ordering is case-insensitive); "data/..." vs "data.py" checks
    # component-wise order; no case-only collisions (macOS and Windows file systems are case-insensitive)
    files = {"a.py": b"x = 1\n", "B.py": b"y = 2\n", "data/synthetic.py": b"import os\n", "data.py": b"z = 3\n", "a-b.py": b"\n"}
    for rel, data in files.items():
        (tmp_path / "lf" / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / "lf" / rel).write_bytes(data)
        (tmp_path / "crlf" / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / "crlf" / rel).write_bytes(data.replace(b"\n", b"\r\n"))
    (tmp_path / "lf" / "__pycache__").mkdir()
    (tmp_path / "lf" / "__pycache__" / "a.py").write_bytes(b"ignored")
    expected = hashlib.sha256()
    for rel in sorted(files, key=lambda r: tuple(r.split("/"))):   # case-sensitive component order, "/" separators
        expected.update(rel.encode("utf-8") + files[rel])
    assert source_tree_sha256(tmp_path / "lf") == source_tree_sha256(tmp_path / "crlf") == expected.hexdigest()


def test_definition_file_hash_ignores_crlf_only(tmp_path):
    from falls_ml.artifacts import definition_file_sha256

    lf, crlf, changed = tmp_path / "lf.yaml", tmp_path / "crlf.yaml", tmp_path / "changed.yaml"
    lf.write_bytes(b"a: 1\nb: 2\n")
    crlf.write_bytes(b"a: 1\r\nb: 2\r\n")
    changed.write_bytes(b"a: 1\nb: 3\n")
    assert definition_file_sha256(lf) == definition_file_sha256(crlf) == hashlib.sha256(lf.read_bytes()).hexdigest()
    assert definition_file_sha256(changed) != definition_file_sha256(lf)


