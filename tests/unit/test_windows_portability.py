# ============================================================================ AST scanning helpers
@dataclass(frozen=True)
class Site:
    path: str
    line: int
    function: str
    rule: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line} ({self.function}): {self.rule}"


def _python_files(dirs: tuple[str, ...]) -> list[Path]:
    return sorted(p for d in dirs for p in (ROOT / d).rglob("*.py") if "__pycache__" not in p.parts)


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _has_kw(call: ast.Call, name: str) -> bool:
    return any(k.arg == name for k in call.keywords)


def _kw(call: ast.Call, name: str) -> ast.expr | None:
    return next((k.value for k in call.keywords if k.arg == name), None)


def _literal_str(node: ast.expr | None) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def _is_false(node: ast.expr | None) -> bool:
    return isinstance(node, ast.Constant) and node.value in (False, None, 0)


def _dotted(node: ast.expr) -> tuple[str, str] | None:
    """('module', 'attr') for ``module.attr`` expressions."""
    if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
        return node.value.id, node.attr
    return None


class _Visitor(ast.NodeVisitor):
    """Walks one module keeping the enclosing function name and whether we are inside ``try: ... except OSError``."""

    def __init__(self) -> None:
        self.functions: list[ast.FunctionDef | ast.AsyncFunctionDef] = []
        self.oserror_try_depth = 0
        self.calls: list[tuple[ast.Call, str, bool, list[ast.expr]]] = []
        self.imports: list[tuple[int, str, str]] = []
        self.attributes: list[tuple[ast.Attribute, str]] = []

    def _function(self) -> str:
        return self.functions[-1].name if self.functions else "<module>"

    def visit_FunctionDef(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> None:
        self.functions.append(node)
        self.generic_visit(node)
        self.functions.pop()

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_Try(self, node: ast.Try) -> None:
        catches = any(h.type is None or any(isinstance(n, ast.Name) and n.id in {"OSError", "Exception", "NotImplementedError"}
                                            for n in ast.walk(h.type)) for h in node.handlers)
        self.oserror_try_depth += catches
        for stmt in node.body:
            self.visit(stmt)
        self.oserror_try_depth -= catches
        for part in (*node.handlers, *node.orelse, *node.finalbody):
            self.visit(part)

    visit_TryStar = visit_Try

    def visit_Call(self, node: ast.Call) -> None:
        decorators = [d for f in self.functions for d in f.decorator_list]
        self.calls.append((node, self._function(), self.oserror_try_depth > 0, decorators))
        self.generic_visit(node)

    def visit_Import(self, node: ast.Import) -> None:
        self.imports += [(node.lineno, alias.name.split(".")[0], self._function()) for alias in node.names]

    def visit_ImportFrom(self, node: ast.ImportFrom) -> None:
        if node.module and node.level == 0:
            self.imports.append((node.lineno, node.module.split(".")[0], self._function()))

    def visit_Attribute(self, node: ast.Attribute) -> None:
        self.attributes.append((node, self._function()))
        self.generic_visit(node)


def _visit(path: Path) -> _Visitor:
    visitor = _Visitor()
    visitor.visit(ast.parse(path.read_bytes(), filename=str(path)))
    return visitor


def _open_mode(call: ast.Call, positional_index: int) -> str | None:
    """Literal mode of an open-like call ('r' when omitted); None when the mode is not a literal."""
    mode = _kw(call, "mode")
    if mode is None and len(call.args) > positional_index:
        mode = call.args[positional_index]
    if mode is None:
        return "r"
    return _literal_str(mode)


def text_io_without_encoding(path: Path) -> list[Site]:
    """Text-mode file and pipe I/O that would use the Windows ANSI code page."""
    rel, sites = _rel(path), []
    for call, function, _, _ in _visit(path).calls:
        func = call.func
        name = func.id if isinstance(func, ast.Name) else func.attr if isinstance(func, ast.Attribute) else None
        dotted = _dotted(func)
        encoded = _has_kw(call, "encoding")
        rule = None
        if name in {"read_text", "write_text"} and isinstance(func, ast.Attribute):
            if not encoded and len(call.args) <= (0 if name == "read_text" else 1):
                rule = f"{name}() without encoding"
        elif name == "open" and (isinstance(func, ast.Name) or dotted == ("io", "open")):
            mode = _open_mode(call, 1)
            if not encoded and len(call.args) <= 3 and (mode is None or "b" not in mode):
                rule = f"open() text mode {mode!r} without encoding"
        elif name == "open" and isinstance(func, ast.Attribute) and (dotted is None or dotted[0] not in NON_PATH_OPEN_RECEIVERS):
            first = _literal_str(call.args[0]) if call.args else None
            if call.args and first is not None and not MODE_LITERAL.fullmatch(first):
                continue  # e.g. ZipFile.open("member"): not a Path.open mode
            mode = _open_mode(call, 0)
            if not encoded and len(call.args) <= 2 and (mode is None or "b" not in mode):
                rule = f"Path.open() text mode {mode!r} without encoding"
        elif dotted == ("os", "fdopen"):
            mode = _open_mode(call, 1)
            if not encoded and (mode is None or "b" not in mode):
                rule = f"os.fdopen() text mode {mode!r} without encoding"
        elif name in {"NamedTemporaryFile", "TemporaryFile", "SpooledTemporaryFile"}:
            mode = _open_mode(call, 1 if name == "SpooledTemporaryFile" else 0)
            if mode == "r":
                mode = "w+b"  # tempfile default
            if not encoded and (mode is None or "b" not in mode):
                rule = f"{name}() text mode {mode!r} without encoding"
        elif name == "TextIOWrapper":
            if not encoded and len(call.args) < 2:
                rule = "TextIOWrapper() without encoding"
        elif name in SUBPROCESS_FUNCS and (dotted is None or dotted[0] == "subprocess"):
            text = [_kw(call, k) for k in ("text", "universal_newlines") if _has_kw(call, k)]
            if any(not _is_false(t) for t in text) and not encoded:
                rule = f"subprocess.{name}() text mode without encoding"
        if rule:
            sites.append(Site(rel, call.lineno, function, rule))
    return sites


def lf_artifact_writes(path: Path) -> list[Site]:
    """Text written by src/ and tools/ must use LF on every OS (Windows text mode and pandas default to CRLF)."""
    rel, sites = _rel(path), []
    for call, function, _, _ in _visit(path).calls:
        func = call.func
        if not isinstance(func, ast.Attribute):
            continue
        if func.attr == "write_text" and not _has_kw(call, "newline"):
            sites.append(Site(rel, call.lineno, function, 'write_text() without newline="\\n"'))
        elif func.attr == "to_csv" and not _has_kw(call, "lineterminator"):
            sites.append(Site(rel, call.lineno, function, 'DataFrame.to_csv() without lineterminator="\\n"'))
        elif func.attr == "open" and _dotted(func) is None:
            mode = _open_mode(call, 0)
            if mode is not None and "b" not in mode and set(mode) & set("wax") and not _has_kw(call, "newline"):
                sites.append(Site(rel, call.lineno, function, f'Path.open({mode!r}) without newline="\\n"'))
    return sites


def shell_and_posix_only(path: Path) -> list[Site]:
    rel, sites, visitor = _rel(path), [], _visit(path)
    for call, function, _, _ in visitor.calls:
        if _has_kw(call, "shell") and not _is_false(_kw(call, "shell")):
            sites.append(Site(rel, call.lineno, function, "shell=True (CMD quoting and injection differ from POSIX shells)"))
        if _dotted(call.func) in SHELL_CALLS:
            sites.append(Site(rel, call.lineno, function, f"{'.'.join(_dotted(call.func))}() runs a shell"))
    sites += [Site(rel, line, function, f"Unix-only module {module!r}") for line, module, function in visitor.imports if module in UNIX_ONLY_MODULES]
    sites += [Site(rel, node.lineno, function, f"POSIX-only {'.'.join(_dotted(node))}") for node, function in visitor.attributes
              if _dotted(node) in POSIX_ONLY_ATTRIBUTES]
    return sites


def unguarded_symlinks(path: Path) -> list[Site]:
    """Symlink creation needs admin rights or Developer Mode on Windows: handle OSError or skip on win32."""
    rel, sites = _rel(path), []
    for call, function, in_oserror_try, decorators in _visit(path).calls:
        func = call.func
        name = func.attr if isinstance(func, ast.Attribute) else func.id if isinstance(func, ast.Name) else None
        if name not in {"symlink_to", "symlink", "hardlink_to", "link"} or (name in {"symlink", "link"} and _dotted(func) != ("os", name)):
            continue
        skips_windows = any("skipif" in ast.unparse(d) and ("win32" in ast.unparse(d) or "os.name" in ast.unparse(d)) for d in decorators)
        if not (in_oserror_try or skips_windows):
            sites.append(Site(rel, call.lineno, function, f"{name}() without OSError handling or a Windows skip"))
    return sites


def _shipped_paths() -> Iterator[Path]:
    yield from (p for p in ROOT.iterdir() if p.is_file() and not p.name.startswith("."))
    for top in SHIPPED_DIRS:
        for p in sorted((ROOT / top).rglob("*")):
            if not NOT_SHIPPED_PARTS & set(p.parts) and not any(part.endswith(".egg-info") for part in p.parts):
                yield p


def windows_name_problems(paths: list[Path]) -> list[str]:
    problems = []
    by_folder: dict[tuple[str, str], list[str]] = {}
    for p in paths:
        rel = p.relative_to(ROOT).as_posix()
        name = p.name
        if name.split(".")[0].rstrip(" ").lower() in RESERVED_STEMS:
            problems.append(f"{rel}: reserved Windows device name")
        if INVALID_NAME_CHARS & set(name) or any(ord(c) < 32 for c in name):
            problems.append(f"{rel}: character not allowed in Windows file names")
        if name.endswith((".", " ")):
            problems.append(f"{rel}: trailing dot or space is dropped by Windows")
        if len(rel) > MAX_SHIPPED_RELATIVE_PATH:
            problems.append(f"{rel}: {len(rel)} characters (limit {MAX_SHIPPED_RELATIVE_PATH}; Windows MAX_PATH is 260 including the folder)")
        by_folder.setdefault((p.parent.relative_to(ROOT).as_posix(), name.lower()), []).append(name)
    problems += [f"{folder}: names differ only in case {sorted(names)}" for (folder, _), names in by_folder.items() if len(names) > 1]
    return problems


