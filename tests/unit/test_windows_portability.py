def test_cli_console_streams_backslashreplace_on_ansi_code_pages(monkeypatch):
    from falls_ml import cli

    # newline="\n": on Windows a default TextIOWrapper writes "\r\n"; this test is about encoding, not line endings
    cp1252_out, cp1252_err = (io.TextIOWrapper(io.BytesIO(), encoding="cp1252", newline="\n") for _ in range(2))
    utf8 = io.TextIOWrapper(io.BytesIO(), encoding="utf-8", newline="\n")
    monkeypatch.setattr(sys, "stdout", cp1252_out)
    monkeypatch.setattr(sys, "stderr", cp1252_err)
    cli._safe_console_streams()
    print(f"dataset_version meuhedet-{HEBREW}-v1 \u2013 ok")
    sys.stdout.flush()
    assert cp1252_out.buffer.getvalue() == b"dataset_version meuhedet-\\u05de\\u05d0\\u05d5\\u05d7\\u05d3\\u05ea-v1 \x96 ok\n"
    assert cp1252_err.errors == "backslashreplace"
    monkeypatch.setattr(sys, "stdout", utf8)
    cli._safe_console_streams()
    assert utf8.errors == "strict", "UTF-8 streams are left alone"


def test_cli_prints_non_ascii_table_through_a_cp1252_pipe(tmp_path):
    """``python -m falls_ml compare > out.txt`` from plain CMD on a cp1252 system with a Hebrew dataset_version."""
    from tests.helpers.fake_run import make_fake_run

    make_fake_run(tmp_path / "runs", kind="efalls_published_scoring", model="efalls_published", seed=1,
                  dataset_version=f"meuhedet-{HEBREW}-v1", n_test=200)
    env = {k: v for k, v in os.environ.items() if k not in {"PYTHONUTF8", "PYTHONIOENCODING", "PYTHONLEGACYWINDOWSSTDIO"}}
