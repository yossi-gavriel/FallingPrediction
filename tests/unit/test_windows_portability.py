    result = subprocess.run([sys.executable, "-m", "falls_ml", "compare", "--runs-dir", "runs", "--out", "reports", "--n-bootstrap", "5"],
                            cwd=tmp_path, capture_output=True, env=env, timeout=300, check=False)
    stdout, stderr = result.stdout.decode("cp1252"), result.stderr.decode("cp1252")
    assert result.returncode == 0, stderr[-3000:]
    assert "meuhedet-\\u05de\\u05d0\\u05d5\\u05d7\\u05d3\\u05ea-v1" in stdout
    assert "UnicodeEncodeError" not in stderr
    table, markdown = (tmp_path / "reports" / "comparison.csv").read_bytes(), (tmp_path / "reports" / "comparison.md").read_bytes()
    assert f"meuhedet-{HEBREW}-v1".encode("utf-8") in table and b"\r" not in table + markdown, "reports stay UTF-8 with LF"


