def _fake_bundle(tmp_path: Path) -> tuple[Path, Path, Path, dict]:
    """Two fake wheels + matching locks + manifest for the Windows target."""
    dest = tmp_path / "offline packages"
    dest.mkdir()
    blobs = {"demo_lib-1.0-cp313-cp313-win_amd64.whl": b"demo-win", "colorama-0.4.6-py2.py3-none-any.whl": b"colorama",
             "pip-26.2.1-py3-none-any.whl": b"pip"}
    digests = {name: hashlib.sha256(data).hexdigest() for name, data in blobs.items()}
    for name, data in blobs.items():
        (dest / name).write_bytes(data)
    runtime = tmp_path / "requirements.lock"
    runtime.write_text(
        "# test\n"
        f"demo-lib==1.0 --hash=sha256:{digests['demo_lib-1.0-cp313-cp313-win_amd64.whl']} --hash=sha256:{HASH_A}\n"
        f'colorama==0.4.6 ; sys_platform == "win32" --hash=sha256:{digests["colorama-0.4.6-py2.py3-none-any.whl"]}\n'
        f'posixonly==1.0 ; sys_platform != "win32" --hash=sha256:{HASH_B}\n', encoding="utf-8")
    build = tmp_path / "requirements-build.lock"
    build.write_text(f"pip==26.2.1 --hash=sha256:{digests['pip-26.2.1-py3-none-any.whl']}\n", encoding="utf-8")
    manifest = {"format": 1, "created_utc": "2026-01-01T00:00:00Z", "target": prepare_offline.target_spec("windows-amd64-cp313")["manifest"],
                "requirements_lock_sha256": lockfile.sha256_file(runtime), "build_lock_sha256": lockfile.sha256_file(build),
                "files": dict(sorted(digests.items()))}
    (dest / prepare_offline.MANIFEST_NAME).write_text(json.dumps(manifest), encoding="utf-8")
    return dest, runtime, build, manifest


def test_windows_target_uses_contract_pip_flags():
    spec = prepare_offline.target_spec("windows-amd64-cp313")
    assert spec["pip_args"] == ["--platform", "win_amd64", "--python-version", "3.13", "--implementation", "cp", "--abi", "cp313"]
    assert spec["manifest"] == {"name": "windows-amd64-cp313", "platform_tags": ["win_amd64"], "python_version": "3.13", "implementation": "cp", "abi": "cp313"}
    assert spec["sys_platform"] == "win32"
    with pytest.raises(prepare_offline.OfflineError):
        prepare_offline.target_spec("linux")


def test_verify_bundle_accepts_matching_bundle_and_reports_problems(tmp_path):
    dest, runtime, build, manifest = _fake_bundle(tmp_path)
    assert prepare_offline.verify_bundle(dest, runtime, build, sys_platform="win32") == []
    assert any("this computer is darwin" in p for p in prepare_offline.verify_bundle(dest, runtime, build, sys_platform="darwin"))
    (dest / "colorama-0.4.6-py2.py3-none-any.whl").write_bytes(b"tampered")
    assert any("not listed in the lock" in p for p in prepare_offline.verify_bundle(dest, runtime, build, sys_platform="win32"))
    (dest / "colorama-0.4.6-py2.py3-none-any.whl").write_bytes(b"colorama")
    runtime.write_text(runtime.read_text(encoding="utf-8") + "# edited\n", encoding="utf-8")
    assert any("different requirements.lock" in p for p in prepare_offline.verify_bundle(dest, runtime, build, sys_platform="win32"))
    assert prepare_offline.verify_bundle(tmp_path / "missing", runtime, build, sys_platform="win32")[0].endswith("not found")


def test_check_wheels_detects_missing_extra_and_incompatible_wheels(tmp_path):
    dest, runtime, build, _ = _fake_bundle(tmp_path)
    reqs = prepare_offline.applicable_requirements(runtime, build, "win32")
    assert set(reqs) == {"demo-lib", "colorama", "pip"}
    (dest / "pip-26.2.1-py3-none-any.whl").unlink()
    (dest / "stray.txt").write_text("x", encoding="utf-8")
    with pytest.raises(prepare_offline.OfflineError) as err:
        prepare_offline.check_wheels(dest, reqs, "windows-amd64-cp313")
    assert "missing wheel for pip==26.2.1" in str(err.value) and "unexpected entry stray.txt" in str(err.value)
    mac_dir = tmp_path / "mac"
    mac_dir.mkdir()
    (mac_dir / "demo_lib-1.0-cp313-cp313-macosx_11_0_arm64.whl").write_bytes(b"a")
    fake = {"demo-lib": [lockfile.Requirement("demo-lib", "1.0", (hashlib.sha256(b"a").hexdigest(),))]}
    with pytest.raises(prepare_offline.OfflineError, match="not compatible with windows-amd64-cp313"):
        prepare_offline.check_wheels(mac_dir, fake, "windows-amd64-cp313")
    assert prepare_offline.check_wheels(mac_dir, fake, "current") == {"demo_lib-1.0-cp313-cp313-macosx_11_0_arm64.whl": hashlib.sha256(b"a").hexdigest()}


def test_planned_removals_only_touches_manifest_listed_files(tmp_path):
    empty = tmp_path / "empty"
    empty.mkdir()
    assert prepare_offline.planned_removals(empty, force=False) == []
    assert prepare_offline.planned_removals(tmp_path / "does-not-exist", force=False) == []
    dest, _, _, manifest = _fake_bundle(tmp_path)
    with pytest.raises(prepare_offline.OfflineError, match="not empty"):
        prepare_offline.planned_removals(dest, force=False)
    planned = prepare_offline.planned_removals(dest, force=True)
    assert sorted(p.name for p in planned) == sorted([*manifest["files"], prepare_offline.MANIFEST_NAME])
    (dest / "notes.txt").write_text("user file", encoding="utf-8")
    with pytest.raises(prepare_offline.OfflineError, match="notes.txt"):
        prepare_offline.planned_removals(dest, force=True)
    (dest / "notes.txt").unlink()
    manifest["files"]["../outside.whl"] = HASH_A
    (dest / prepare_offline.MANIFEST_NAME).write_text(json.dumps(manifest), encoding="utf-8")
    with pytest.raises(prepare_offline.OfflineError, match="invalid file names"):
        prepare_offline.planned_removals(dest, force=True)
    (dest / prepare_offline.MANIFEST_NAME).unlink()
    with pytest.raises(prepare_offline.OfflineError, match="no OFFLINE_MANIFEST.json"):
        prepare_offline.planned_removals(dest, force=True)
    assert len(list(dest.iterdir())) == 3  # nothing was deleted by any check


